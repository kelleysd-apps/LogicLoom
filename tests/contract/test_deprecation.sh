#!/usr/bin/env bash
# Contract Tests: Legacy Cleanup Validation (Post Plugin-First v4.0)
# Validates that ALL monolithic legacy artifacts have been removed
# and all capabilities are served exclusively through plugins.
set -euo pipefail

PASS=0; FAIL=0; TOTAL=0; SKIP=0
BRIDGE_MARKER="AUTO-GENERATED by plugin-bridge"

assert() {
  TOTAL=$((TOTAL + 1))
  local desc="$1"; local condition="$2"
  if eval "$condition"; then
    echo "  ✅ PASS: $desc"; PASS=$((PASS + 1))
  else
    echo "  ❌ FAIL: $desc"; FAIL=$((FAIL + 1))
  fi
}
skip() { SKIP=$((SKIP + 1)); echo "  ⏭️  SKIP: $1"; }

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
if ROOT="$(git -C "$SCRIPT_DIR" rev-parse --show-toplevel 2>/dev/null)"; then :; else
  ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
fi
cd "$ROOT"

# shellcheck source=/dev/null
source "$ROOT/tests/lib/tree-provenance.sh"
TREE_KIND="$(loom_tree_kind "$ROOT")"

echo "═══ Legacy Cleanup Validation Tests ═══"
echo "tree kind: $TREE_KIND"
echo ""

if [ "$TREE_KIND" = "inconsistent" ]; then
  loom_require_consistent_tree "$ROOT" || true
  echo "═══════════════════════════════════════"
  echo " Results: ${PASS}/${TOTAL} passed, ${FAIL} failed, ${SKIP} skipped"
  echo "═══════════════════════════════════════"
  exit 1
fi

# ── Monolithic skills removed ──
# .claude/skills/ is now a SANCTIONED location for project-local skills
# converted from a retired plugin (release-migration registry, v7.0.0 —
# .docs/guides/MIGRATION_GUIDE.md). A converted skill carries a
# `converted-from:` marker; anything under .claude/skills/ WITHOUT that
# marker is either a stray or one of the 32 pre-v4.0 monolithic legacy
# skills reappearing, and both are violations.
echo "Monolithic skills removed"
case "$TREE_KIND" in
  maintainer)
    assert "No .claude/skills/ directory exists (harness tree ships no .claude/skills/)" "[ ! -d .claude/skills ]"
    ;;
  sanitized)
    skip "No .claude/skills/ directory — sanitized/adopted tree may hold converted project-local skills"
    ;;
esac

# The union of monolithic skill names across v1.0.0-v3.1.3 (depth-4 layout:
# .claude/skills/<department>/<skill>/SKILL.md), 32 names total (CD-3 in the
# migration design: the department dirs themselves — creation, domain, git,
# governance, integration, orchestration, project-initialization, sdd-workflow,
# technical, validation — are depth-3 and are NOT skill names).
LEGACY_SKILLS="api-design backend-operations constitutional-compliance create-skill create-template database-operations debug devops-operations domain-detection file-organization framework-updater frontend-operations full-stack-feature git-push-workflow governance-preflight mcp-server-setup message-preflight migration-workflow monitoring multi-skill-workflow performance-operations planning-agent qa-validation schema-design sdd-planning sdd-specification sdd-tasks security-operations service-architecture system-design testing-operations unified-specification"

LEGACY_HITS=""
if [ -d "$ROOT/.claude/skills" ]; then
  for name in $LEGACY_SKILLS; do
    for candidate in "$ROOT/.claude/skills/$name/SKILL.md" "$ROOT"/.claude/skills/*/"$name"/SKILL.md; do
      [ -f "$candidate" ] || continue
      if ! head -20 "$candidate" 2>/dev/null | grep -q "converted-from:"; then
        LEGACY_HITS="${LEGACY_HITS}${candidate}"$'\n'
      fi
    done
  done
fi
[ -n "$LEGACY_HITS" ] && printf '%s' "$LEGACY_HITS" | sed 's/^/     legacy skill without converted-from: marker: /'
assert "No legacy monolithic skill reappeared in .claude/skills/ (converted project-local skills are OK)" \
  "[ -z \"\$LEGACY_HITS\" ]"

# ── Monolithic agents removed ──
# NOTE: .claude/agents/ is now a SANCTIONED location for project-level ladder
# agents (deep-reasoner / fast-worker). They MUST be project files to retain
# hooks / permissionMode enforcement — plugin-packaged agents strip those
# fields. So the deprecation invariant is not "no .claude/agents/ dir" but
# "the LEGACY monolithic agents (converted to plugin skills in v4/v5) have not
# reappeared there". See .docs/architecture/orchestrator-worker-ladder.md.
echo ""
echo "Monolithic agents removed"
LEGACY_AGENTS="$(ls .claude/agents/ 2>/dev/null | grep -Ei 'task-orchestrator|swarm-coordinator|workflow-coordinator|specification-agent|planning-agent|tasks-agent|specification-orchestrator|sdd-domain-' || true)"
assert "No legacy monolithic agents in .claude/agents/ (project ladder agents are OK)" "[ -z \"$LEGACY_AGENTS\" ]"

# ── Legacy indexes removed ──
echo ""
echo "Legacy indexes removed"
assert "No .claude/skill-index.json" "[ ! -f .claude/skill-index.json ]"
assert "No .claude/agent-index.json" "[ ! -f .claude/agent-index.json ]"

# ── Old constitution versions removed ──
echo ""
echo "Old constitution archives removed"
assert "No constitution-v1.6.0-archive.md" "[ ! -f .logic-loom/memory/constitution-v1.6.0-archive.md ]"
assert "No constitution-v2.0.0-draft.md" "[ ! -f .logic-loom/memory/constitution-v2.0.0-draft.md ]"

# ── All commands are bridge-generated (no deprecated statics) ──
echo ""
echo "All commands served via plugin bridge"
STATIC_COUNT=0
BRIDGE_COUNT=0
for cmd_file in .claude/commands/*.md; do
  [ -f "$cmd_file" ] || continue
  if grep -q -- "$BRIDGE_MARKER" <<< "$(head -10 "$cmd_file")"; then
    BRIDGE_COUNT=$((BRIDGE_COUNT + 1))
  else
    STATIC_COUNT=$((STATIC_COUNT + 1))
    echo "  ⚠️  Non-bridge command: $(basename "$cmd_file")"
  fi
done
assert "No static commands remain (found ${STATIC_COUNT})" "[ $STATIC_COUNT -eq 0 ]"
assert "All 15 commands are bridge-generated (found ${BRIDGE_COUNT})" "[ $BRIDGE_COUNT -ge 15 ]"

# ── Plugins are authoritative ──
echo ""
echo "Plugin-First completeness (v4.0)"
assert "framework-updater has plugin home" "[ -f plugins/loom-maintenance/skills/framework-updater/SKILL.md ]"
assert "mcp-server-setup has plugin home" "[ -f plugins/loom-maintenance/skills/mcp-server-setup/SKILL.md ]"
assert "project-initialization has plugin home" "[ -f plugins/loom-maintenance/skills/project-initialization/SKILL.md ]"
assert "create-plugin command exists" "[ -f plugins/loom-creation/commands/create-plugin.md ]"
assert "create-plugin skill exists" "[ -f plugins/loom-creation/skills/create-plugin/SKILL.md ]"
assert "loom-maintenance plugin manifest exists" "[ -f plugins/loom-maintenance/.claude-plugin/plugin.json ]"

echo ""
echo "Plugin Command Bridge (v4.1)"
assert "Bridge script exists" "[ -x .logic-loom/scripts/bash/sync-plugin-commands.sh ]"
assert "Bridge manifest exists" "[ -f .claude/commands/.bridge-manifest.json ]"
assert "Bridge manifest is valid JSON" "python3 -c 'import json; json.load(open(\".claude/commands/.bridge-manifest.json\"))'"
assert "Bridge manifest has no statics" "python3 -c 'import json,sys; d=json.load(open(\".claude/commands/.bridge-manifest.json\")); sys.exit(0 if len(d.get(\"static\",[])) == 0 else 1)'"

echo ""
echo "Backup files cleaned"
assert "No .bak files in .claude/" "[ \$(find .claude -name '*.bak' 2>/dev/null | wc -l | tr -d ' ') -eq 0 ]"
assert "No .backup files in root" "[ \$(find . -maxdepth 1 -name '*backup*' 2>/dev/null | wc -l | tr -d ' ') -eq 0 ]"

echo ""
echo "═══════════════════════════════════════"
echo " Results: ${PASS}/${TOTAL} passed, ${FAIL} failed, ${SKIP:-0} skipped"
echo "═══════════════════════════════════════"
[ $FAIL -eq 0 ] && exit 0 || exit 1
